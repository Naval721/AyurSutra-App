interface SessionPlan {
  therapy: string;
  stage: TreatmentStage;
  duration: number;
  therapist: string;
  room: string;
}

function buildSessions(
  treatmentId: string,
  startOffset: number,
  plans: SessionPlan[],
): TreatmentSession[] {
  return plans.map((plan, index) => {
    const dayOffset = startOffset + index;
    let status: TreatmentSession['status'] = 'pending';
    if (dayOffset < 0) status = 'completed';
    else if (dayOffset === 0) status = index % 2 === 0 ? 'completed' : 'in_progress';

    return {
      id: `${treatmentId}-s${index + 1}`,
      day: index + 1,
      date: ymd(dayOffset),
      stage: plan.stage,
      therapy_name: plan.therapy,
      therapist_id: plan.therapist,
      room: plan.room,
      duration_min: plan.duration,
      status,
      notes: null,
    };
  });
}

