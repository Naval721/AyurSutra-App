function dinacharya(done: number): DinacharyaState {
  const state: DinacharyaState = {
    wake_early: false,
    oil_pulling: false,
    abhyanga: false,
    yoga: false,
    warm_meals: false,
    early_dinner: false,
    sleep_early: false,
  };
  const keys: DinacharyaKey[] = [
    'wake_early',
    'oil_pulling',
    'abhyanga',
    'yoga',
    'warm_meals',
    'early_dinner',
    'sleep_early',
  ];
  keys.forEach((key, index) => {
    state[key] = index < done;
  });
  return state;
}

